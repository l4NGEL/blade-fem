#!/usr/bin/env python3
"""Generate meshes/blade.geo: a cooled turbine-blade section for Gmsh.

The aerofoil is a NACA 4-digit profile with a closed trailing edge, made heavily
cambered and thick so that it reads as a turbine rather than a wing section. It is
a simplified, illustrative geometry, not a real engine blade.

Boundaries (Gmsh physical names):
  leading_edge   the stagnation region, x/c < LE_FRACTION on both sides
  suction_side   convex (upper) surface downstream of the leading edge
  pressure_side  concave (lower) surface downstream of the leading edge
  cooling        the walls of all internal cooling passages
Surface: blade

--te-passage adds a fourth, small passage at 80 % chord (design variant).

The mesh size is a Gmsh constant, so one .geo serves every refinement level:
  gmsh meshes/blade.geo -2 -format msh22 -setnumber lc 0.0006 -o meshes/blade.msh
"""

import argparse
import math
from pathlib import Path

CHORD = 0.050          # m
CAMBER = 0.07          # max camber / chord   (NACA "m")
CAMBER_POS = 0.40      # position of max camber / chord ("p")
THICKNESS = 0.22       # max thickness / chord ("t")
POINTS_PER_SIDE = 90
LE_FRACTION = 0.06     # extent of the leading-edge boundary along the chord
HOLES = [(0.22, 0.42), (0.43, 0.42), (0.63, 0.40)]  # (x/c, radius / local half-thickness)
TE_PASSAGE = (0.80, 0.38)  # optional extra passage near the trailing edge


def camber(x):
    """Camber line y_c(x) and its slope, x in chord fractions."""
    m, p = CAMBER, CAMBER_POS
    if x < p:
        return m / p**2 * (2 * p * x - x * x), 2 * m / p**2 * (p - x)
    return m / (1 - p) ** 2 * ((1 - 2 * p) + 2 * p * x - x * x), 2 * m / (1 - p) ** 2 * (p - x)


def half_thickness(x):
    """NACA thickness distribution with the closed-trailing-edge coefficient."""
    return 5 * THICKNESS * (0.2969 * math.sqrt(x) - 0.1260 * x - 0.3516 * x**2 + 0.2843 * x**3 - 0.1036 * x**4)


def surface(x, sign):
    yc, slope = camber(x)
    th = math.atan(slope)
    yt = half_thickness(x)
    return (x - sign * yt * math.sin(th)) * CHORD, (yc + sign * yt * math.cos(th)) * CHORD


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("-o", "--output", default=None, help="default: meshes/blade.geo or meshes/blade_te.geo")
    parser.add_argument("--te-passage", action="store_true", help="add a fourth passage near the trailing edge")
    args = parser.parse_args()
    meshes = Path(__file__).resolve().parent.parent / "meshes"
    output = Path(args.output) if args.output else meshes / ("blade_te.geo" if args.te_passage else "blade.geo")
    holes = HOLES + ([TE_PASSAGE] if args.te_passage else [])

    # Cosine spacing clusters points at the leading and trailing edges.
    xs = [0.5 * (1 - math.cos(math.pi * i / POINTS_PER_SIDE)) for i in range(POINTS_PER_SIDE + 1)]
    upper = [surface(x, +1) for x in xs]           # LE -> TE
    lower = [surface(x, -1) for x in xs]           # LE -> TE
    split = next(i for i, x in enumerate(xs) if x >= LE_FRACTION)

    out = []
    w = out.append
    w("// Cooled turbine-blade section - generated by scripts/make_blade_geo.py, do not edit.")
    w(f"// NACA-type profile m={CAMBER} p={CAMBER_POS} t={THICKNESS}, chord {CHORD * 1e3:.0f} mm.")
    w("DefineConstant[ lc = {0.0008, Name 'Mesh size [m]'} ];")
    w("DefineConstant[ hole_refine = {0.5, Name 'Size factor at cooling holes'} ];")
    w("Mesh.ElementOrder = 1;")
    w("Mesh.Algorithm = 6;  // Frontal-Delaunay")
    w("")

    pid = 0
    def point(x, y, size="lc"):
        nonlocal pid
        pid += 1
        w(f"Point({pid}) = {{{x:.9f}, {y:.9f}, 0, {size}}};")
        return pid

    # Shared LE (index 0) and TE (index -1) points.
    le = point(*upper[0], "lc*0.5")
    up_ids = [le] + [point(*p, "lc*0.5" if i < split else "lc") for i, p in enumerate(upper[1:-1], start=1)]
    te = point(*upper[-1], "lc*0.5")
    up_ids.append(te)
    lo_ids = [le] + [point(*p, "lc*0.5" if i < split else "lc") for i, p in enumerate(lower[1:-1], start=1)] + [te]

    def ids(seq):
        return ", ".join(str(i) for i in seq)

    w("")
    # Closed loop: suction side LE->TE, pressure side TE->LE, split at the leading-edge region.
    w(f"Spline(1) = {{{ids(up_ids[split:])}}};                 // suction side")
    w(f"Spline(2) = {{{ids(list(reversed(lo_ids[split:])))}}};  // pressure side")
    w(f"Spline(3) = {{{ids(list(reversed(lo_ids[:split + 1])) + up_ids[1:split + 1])}}};  // leading edge")
    w("Curve Loop(1) = {1, 2, 3};")
    w("")

    loops = [1]
    curve = 10
    hole_curves = []
    for k, (xc, rfrac) in enumerate(holes, start=1):
        yc, _ = camber(xc)
        cx, cy = xc * CHORD, yc * CHORD
        r = rfrac * half_thickness(xc) * CHORD
        w(f"// cooling passage {k}: centre ({cx * 1e3:.2f}, {cy * 1e3:.2f}) mm, radius {r * 1e3:.2f} mm")
        c = point(cx, cy, "lc*hole_refine")
        rim = [point(cx + r * math.cos(a), cy + r * math.sin(a), "lc*hole_refine")
               for a in (0, math.pi / 2, math.pi, 3 * math.pi / 2)]
        arcs = []
        for j in range(4):
            curve += 1
            w(f"Circle({curve}) = {{{rim[j]}, {c}, {rim[(j + 1) % 4]}}};")
            arcs.append(curve)
        hole_curves += arcs
        loops.append(10 + k)
        w(f"Curve Loop({10 + k}) = {{{ids(arcs)}}};")

    w("")
    w(f"Plane Surface(1) = {{{ids(loops)}}};")
    w('Physical Curve("suction_side", 1) = {1};')
    w('Physical Curve("pressure_side", 2) = {2};')
    w('Physical Curve("leading_edge", 3) = {3};')
    w(f'Physical Curve("cooling", 4) = {{{ids(hole_curves)}}};')
    w('Physical Surface("blade", 10) = {1};')

    path = output
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:  # identical bytes on every OS
        fh.write("\n".join(out) + "\n")

    # Support points for the structural model: on the camber line between passages,
    # where there is always material.
    for x in (0.33, 0.53):
        yc, _ = camber(x)
        print(f"solid point on camber line x/c={x}: ({x * CHORD:.6f}, {yc * CHORD:.6f})")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
